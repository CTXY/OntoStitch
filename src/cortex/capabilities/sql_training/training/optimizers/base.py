class OptimizerDispatchError(ValueError):
    """An owner optimizer could not satisfy its frozen candidate contract."""


def extract_owner_optimizer_result(
    llm: object,
    record: dict[str, Any],
    prompt: str,
    *,
    trace_capture: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    output_model = _optimizer_output_model(record)
    rows = run_llm_extraction(
        llm=llm,
        prompt=prompt,
        output_model=output_model,
        human_payload=record,
        map_result=lambda parsed: [output_model.model_validate(parsed).model_dump(mode="json")],
        trace_capture=trace_capture,
    )
    return rows


def _optimizer_output_model(record: dict[str, Any]) -> type[NodeModel]:
    mode = str(record.get("mode") or "")
    owner = str(record.get("optimizer_owner") or "")
    if not owner and mode == "initialize":
        group = record.get("initialization_group")
        owner = str(group.get("owner") or "") if isinstance(group, dict) else ""
    if not owner and mode == "refine":
        candidate = record.get("candidate")
        asset = candidate.get("asset") if isinstance(candidate, dict) else None
        node_type = str(asset.get("node_type") or "") if isinstance(asset, dict) else ""
        owner = "semantic_mapping" if node_type == "concept" else node_type

    models: dict[tuple[str, str], type[NodeModel]] = {
        ("initialize", "semantic_mapping"): ConceptInitializationLLMOutput,
        ("initialize", "metric"): MetricInitializationLLMOutput,
        ("initialize", "generation_rule"): GenerationRuleInitializationLLMOutput,
        ("refine", "semantic_mapping"): ConceptRefinementLLMOutput,
        ("refine", "metric"): MetricRefinementLLMOutput,
        ("refine", "generation_rule"): GenerationRuleRefinementLLMOutput,
    }
    if model := models.get((mode, owner)):
        return model
    return OwnerRefinementLLMOutput if mode == "refine" else OwnerInitializationLLMOutput


class BaseAssetOptimizer:
    def __init__(self, provider: Any, *, owner: OptimizationOwner, prompt_name: str):
        self.provider = provider
        self.owner = owner
        self.prompt_name = prompt_name

    def initialize(
        self,
        group: InitializationGroup,
        plan: HeavyRoundPlan,
        working: CaseWorkingOntology,
        *,
        accepted_working: CaseWorkingOntology | None = None,
        evidence: dict[str, Any],
        max_attempts: int = 3,
    ) -> CandidateInitializationResult:
        if group.owner != self.owner:
            raise ValueError("optimizer owner does not match initialization group")
        requirements = {
            requirement.requirement_id: requirement
            for owner_plan in plan.owner_plans
            if owner_plan.target_id in group.target_ids
            for requirement in owner_plan.required_assets
            if requirement.requirement_id in group.requirement_ids
        }
        accepted_assets = list((accepted_working or working).assets)
        base_asset = next(
            (
                asset
                for asset in accepted_assets
                if asset.id == group.base_asset_id
            ),
            None,
        )
        payload = {
            **evidence,
            "mode": "initialize",
            "optimizer_owner": self.owner.value,
            "initialization_group": group.model_dump(mode="json"),
            "repair_targets": [
                target.model_dump(mode="json")
                for target in plan.targets
                if target.target_id in group.target_ids
            ],
            "asset_requirements": [
                requirements[item].model_dump(mode="json") for item in group.requirement_ids
            ],
            "base_asset": base_asset.model_dump(mode="json") if base_asset else None,
            "working_ontology": _working_ontology_context(working.assets),
        }
        payload.update(self.context(working.assets))
        errors: list[str] = []
        for attempt in range(1, max_attempts + 1):
            request = dict(payload)
            if errors:
                request["validation_feedback"] = {
                    "attempt": attempt,
                    "error": errors[-1],
                    "instruction": self.retry_instruction(errors[-1]),
                }
            try:
                raw = self._extract(request)
                output_model = _optimizer_output_model(payload)
                output = output_model.model_validate(raw)
                result = _build_initialization_result(
                    group,
                    output,
                    source_id=str(evidence.get("source_id") or "") or None,
                    table_schema=evidence.get("table_schema"),
                )
                validate_initialization_result(group, result)
                self.validate_initialization_identity(base_asset, result)
                _validate_dependency_working_collisions(group, result, accepted_assets)
                validate_cross_candidate_collisions(result.candidates)
                for candidate in result.candidates:
                    self.validate_assets(
                        [candidate.asset, *candidate.dependency_assets],
                        working_assets=working.assets,
                        evidence=evidence,
                    )
                    validate_candidate_references(
                        candidate,
                        working_assets=working.assets,
                        table_schema=evidence.get("table_schema"),
                    )
                return result
            except (ValidationError, ValueError) as exc:
                errors.append(str(exc))
        raise OptimizerDispatchError(
            f"{self.owner.value} initialization failed after {max_attempts} attempts: {errors[-1]}"
        )

    def refine(
        self,
        candidate: CandidateAsset,
        assessment: CandidateAssessment,
        target_assessments: list[TargetAssessment],
        plan: HeavyRoundPlan,
        *,
        evidence: dict[str, Any],
        working: CaseWorkingOntology | None = None,
        max_attempts: int = 3,
    ) -> CandidateAsset:
        payload = {
            **evidence,
            "mode": "refine",
            "optimizer_owner": self.owner.value,
            "candidate": candidate.model_dump(mode="json"),
            "candidate_assessment": assessment.model_dump(mode="json"),
            "owned_target_assessments": [
                item.model_dump(mode="json") for item in target_assessments
            ],
            "preserve": [item.evidence for item in target_assessments if item.status == "resolved"],
            "heavy_round_id": plan.round_id,
        }
        working_assets = list((working or CaseWorkingOntology()).assets)
        payload["working_ontology"] = _working_ontology_context(working_assets)
        payload.update(self.context(working_assets))
        errors: list[str] = []
        for attempt in range(1, max_attempts + 1):
            request = dict(payload)
            if errors:
                request["validation_feedback"] = {
                    "attempt": attempt,
                    "error": errors[-1],
                    "instruction": self.retry_instruction(errors[-1], refinement=True),
                }
            try:
                output_model = _optimizer_output_model(payload)
                output = output_model.model_validate(self._extract(request))
                output_asset = NodeAsset.model_validate(output.asset.model_dump(mode="json"))
                output_dependencies = [
                    NodeAsset.model_validate(asset.model_dump(mode="json"))
                    for asset in getattr(output, "dependency_assets", [])
                ]
                if self.owner == OptimizationOwner.METRIC:
                    output_asset = _canonicalize_metric_references(output_asset)
                    output_dependencies = [
                        _canonicalize_metric_references(asset)
                        for asset in output_dependencies
                    ]
                if output_asset.id != candidate.asset.id:
                    raise ValueError("refinement changed logical asset ID")
                if output_asset.node_type != candidate.asset.node_type:
                    raise ValueError("refinement changed asset type")
                replacement_dependencies = {
                    asset.id: asset for asset in output_dependencies
                }
                original_dependency_ids = [
                    asset.id for asset in candidate.dependency_assets
                ]
                if set(replacement_dependencies) != set(original_dependency_ids):
                    raise ValueError("refinement changed Metric dependency asset identities")
                output_dependencies = [
                    replacement_dependencies[asset_id]
                    for asset_id in original_dependency_ids
                ]
                self.validate_refinement_identity(candidate.asset, output_asset)
                if not output_asset.sources:
                    output_asset.sources = [
                        source.model_copy(deep=True) for source in candidate.asset.sources
                    ]
                for replacement, original in zip(
                    output_dependencies, candidate.dependency_assets, strict=True
                ):
                    if not replacement.sources:
                        replacement.sources = [
                            source.model_copy(deep=True) for source in original.sources
                        ]
                if (
                    output_asset == candidate.asset
                    and output_dependencies == candidate.dependency_assets
                ):
                    raise ValueError("refinement did not materially change asset content")
                if (
                    assessment.application == "not_retrieved"
                    and _retrieval_signature(output_asset)
                    == _retrieval_signature(candidate.asset)
                ):
                    raise ValueError(
                        "retrieval refinement must materially change name, aliases, tags, "
                        "properties.references, or properties.triggers"
                    )
                self.validate_assets(
                    [output_asset, *output_dependencies],
                    working_assets=working_assets,
                    evidence=evidence,
                )
                refined = CandidateAsset(
                    candidate_id=candidate.candidate_id,
                    asset=output_asset,
                    dependency_assets=output_dependencies,
                )
                validate_candidate_references(
                    refined,
                    working_assets=working_assets,
                    table_schema=evidence.get("table_schema"),
                )
                return refined
            except (ValidationError, ValueError) as exc:
                errors.append(str(exc))
        raise OptimizerDispatchError(
            f"{self.owner.value} refinement failed after {max_attempts} attempts: {errors[-1]}"
        )

    def context(self, working_assets: list[NodeAsset]) -> dict[str, Any]:
        del working_assets
        return {}

    def validate_initialization_identity(
        self,
        base_asset: NodeAsset | None,
        result: CandidateInitializationResult,
    ) -> None:
        del base_asset, result

    def validate_refinement_identity(
        self,
        original: NodeAsset,
        replacement: NodeAsset,
    ) -> None:
        del original, replacement

    def validate_assets(
        self,
        assets: list[NodeAsset],
        *,
        working_assets: list[NodeAsset],
        evidence: dict[str, Any],
    ) -> None:
        del assets, working_assets, evidence

    def retry_instruction(self, error: str, *, refinement: bool = False) -> str:
        return _base_retry_instruction(error, refinement=refinement)

    def _extract(self, payload: dict[str, Any]) -> dict[str, Any]:
        trace_capture: dict[str, Any] = {}
        rows = self.provider.extract_assets(
            payload,
            context={
                "prompt_name": self.prompt_name,
                "prompt": load_prompt(self.prompt_name),
                "trace_capture": trace_capture,
            },
        )
        row = rows[0] if rows and isinstance(rows[0], dict) else {}
        return row.get("optimizer_result", row)


def _base_retry_instruction(error: str, *, refinement: bool = False) -> str:
    del error
    if refinement:
        base = (
            "Return one materially improved asset with the exact same logical ID and type. "
            "Apply the concrete feedback and preserve resolved behavior."
        )
    else:
        base = (
            "Return assets that exactly bind every frozen requirement. Preserve operation, "
            "owner, base identity, and concept separation."
        )
    return base


def _retrieval_signature(asset: NodeAsset) -> dict[str, Any]:
    properties = asset.properties.model_dump(mode="json")
    return {
        "name": asset.name,
        "aliases": list(asset.aliases),
        "tags": list(asset.tags),
        "references": properties.get("references"),
        "triggers": properties.get("triggers"),
    }


def _build_initialization_result(
    group: InitializationGroup,
    output: NodeModel,
    *,
    source_id: str | None = None,
    table_schema: Any = None,
) -> CandidateInitializationResult:
    seen_requirements: set[str] = set()
    candidates: list[CandidateAsset] = []
    candidate_id_by_requirement: dict[str, str] = {}
    for index, item in enumerate(output.assets, start=1):
        requirement_ids = list(dict.fromkeys(item.requirement_ids))
        if len(requirement_ids) != len(item.requirement_ids):
            raise ValueError("optimizer output contains duplicate requirement IDs")
        duplicate = seen_requirements.intersection(requirement_ids)
        if duplicate:
            raise ValueError(f"requirements bound by multiple candidates: {sorted(duplicate)}")
        seen_requirements.update(requirement_ids)
        candidate_id = f"{group.owner.value}:{group.requirement_ids[0]}:{index}"
        raw_asset = (
            item.asset.model_dump(mode="json")
            if isinstance(item.asset, NodeModel)
            else item.asset
        )
        asset = _normalize_initialized_asset(group, raw_asset, table_schema=table_schema)
        if source_id and not asset.sources:
            asset.sources = [Source(source_type=SourceType.QA, source_id=source_id)]
        dependency_assets = [
            _normalize_created_metric(
                raw_dependency.model_dump(mode="json")
                if isinstance(raw_dependency, NodeModel)
                else raw_dependency
            )
            for raw_dependency in getattr(item, "dependency_assets", [])
        ]
        if source_id:
            for dependency in dependency_assets:
                if not dependency.sources:
                    dependency.sources = [Source(source_type=SourceType.QA, source_id=source_id)]
        candidates.append(
            CandidateAsset(
                candidate_id=candidate_id,
                asset=asset,
                dependency_assets=dependency_assets,
            )
        )
        for requirement_id in requirement_ids:
            candidate_id_by_requirement[requirement_id] = candidate_id
    return CandidateInitializationResult(
        candidates=candidates,
        candidate_id_by_requirement=candidate_id_by_requirement,
    )


def _normalize_initialized_asset(
    group: InitializationGroup,
    raw_asset: dict[str, Any],
    *,
    table_schema: Any = None,
) -> NodeAsset:
    payload = dict(raw_asset)
    # Runtime evidence owns provenance. Optimizers generate asset content only; accepting their
    # free-form source annotations makes otherwise valid candidates depend on model formatting.
    payload.pop("sources", None)
    if group.owner == OptimizationOwner.METRIC:
        payload = _normalize_metric_expression_ref_keys(payload)
    if group.owner == OptimizationOwner.GENERATION_RULE:
        payload = _resolve_generation_rule_column_references(payload, table_schema)
    if group.operation == "update":
        payload["id"] = group.base_asset_id
    else:
        node_type = NodeType(payload.get("node_type"))
        properties = (
            payload.get("properties") if isinstance(payload.get("properties"), dict) else {}
        )
        identity = payload.get("name") or properties.get("condition")
        if not str(identity or "").strip():
            raise ValueError("CREATE asset requires a stable semantic identity")
        payload["id"] = (
            make_generation_rule_id(rule_name=identity)
            if node_type == NodeType.GENERATION_RULE
            else make_node_id(node_type, identity)
        )
    asset = NodeAsset.model_validate(payload)
    return (
        _canonicalize_metric_references(asset)
        if group.owner == OptimizationOwner.METRIC
        else asset
    )


def _normalize_created_metric(raw_asset: dict[str, Any]) -> NodeAsset:
    payload = _normalize_metric_expression_ref_keys(dict(raw_asset))
    payload.pop("sources", None)
    if NodeType(payload.get("node_type")) != NodeType.METRIC:
        raise ValueError("dependency_assets may contain only Metrics")
    name = str(payload.get("name") or "").strip()
    if not name:
        raise ValueError("dependency Metric requires a stable name")
    asset_id = str(payload.get("id") or "").strip()
    if not asset_id:
        payload["id"] = make_node_id(NodeType.METRIC, name)
    elif not asset_id.startswith("metric."):
        raise ValueError("dependency Metric ID must use the metric.* namespace")
    return _canonicalize_metric_references(NodeAsset.model_validate(payload))


def _working_ontology_context(assets: list[NodeAsset]) -> list[dict[str, Any]]:
    """Expose accepted and earlier same-round assets through one prompt-local view."""

    return [
        asset.model_dump(mode="json")
        for asset in sorted(assets, key=lambda item: (item.node_type.value, item.id))
    ]


def _validate_dependency_working_collisions(
    group: InitializationGroup,
    result: CandidateInitializationResult,
    working_assets: list[NodeAsset],
) -> None:
    if group.operation != "create":
        return
    working_by_id = {asset.id: asset for asset in working_assets}
    collisions = sorted(
        {
            asset.id
            for candidate in result.candidates
            for asset in candidate.dependency_assets
            if asset.id in working_by_id
        }
    )
    if collisions:
        raise ValueError(
            "CREATE dependency_assets collide with accepted Working Ontology identities; "
            f"reuse the existing dependencies by exact ID: {collisions}"
        )


def _canonicalize_metric_references(asset: NodeAsset) -> NodeAsset:
    """Keep Metric references equal to the expression dependency closure."""

    if asset.node_type != NodeType.METRIC:
        return asset
    asset.properties.references = list(
        dict.fromkeys(asset.properties.expression.refs.values())
    )
    return asset


def _visible_metric_context(assets: list[NodeAsset]) -> list[dict[str, Any]]:
    return [
        {
            "id": asset.id,
            "name": asset.name,
            "aliases": list(asset.aliases),
            "expression": asset.properties.expression.model_dump(mode="json"),
        }
        for asset in sorted(assets, key=lambda item: item.id)
        if asset.node_type == NodeType.METRIC
    ]


def _visible_concept_context(assets: list[NodeAsset]) -> list[dict[str, Any]]:
    return [
        {
            "id": asset.id,
            "name": asset.name,
            "aliases": list(asset.aliases),
            "targets": [
                {
                    "sql_expression": target.sql_expression,
                    "references": list(target.references),
                }
                for target in asset.properties.targets
            ],
        }
        for asset in sorted(assets, key=lambda item: item.id)
        if asset.node_type == NodeType.SEMANTIC_MAPPING
    ]


def _normalize_metric_expression_ref_keys(payload: dict[str, Any]) -> dict[str, Any]:
    properties = payload.get("properties")
    if not isinstance(properties, dict):
        return payload
    expression = properties.get("expression")
    if not isinstance(expression, dict) or not isinstance(expression.get("refs"), dict):
        return payload
    normalized_refs: dict[str, Any] = {}
    for raw_key, reference in expression["refs"].items():
        key = str(raw_key).strip()
        if key.startswith("${") and key.endswith("}"):
            key = key[2:-1].strip()
        if not key:
            raise ValueError("Metric expression.refs contains an empty key")
        if key in normalized_refs and normalized_refs[key] != reference:
            raise ValueError(f"Metric expression.refs normalization collides at key: {key}")
        normalized_refs[key] = reference
    normalized = dict(payload)
    normalized_properties = dict(properties)
    normalized_expression = dict(expression)
    normalized_expression["refs"] = normalized_refs
    normalized_properties["expression"] = normalized_expression
    normalized["properties"] = normalized_properties
    return normalized


def _resolve_generation_rule_column_references(
    payload: dict[str, Any],
    table_schema: Any,
) -> dict[str, Any]:
    properties = payload.get("properties")
    if not isinstance(properties, dict):
        return payload
    references = properties.get("references")
    references = references if isinstance(references, list) else []
    triggers = properties.get("triggers")
    triggers = triggers if isinstance(triggers, dict) else {}
    sql_triggers = triggers.get("sql")
    sql_triggers = sql_triggers if isinstance(sql_triggers, dict) else {}
    trigger_columns = sql_triggers.get("columns")
    trigger_columns = trigger_columns if isinstance(trigger_columns, list) else []
    bare_reference_columns = {
        reference.strip()
        for reference in references
        if isinstance(reference, str) and reference.strip() and "." not in reference
    }
    bare_trigger_columns = {
        column.strip()
        for column in trigger_columns
        if isinstance(column, str) and column.strip() and "." not in column
    }
    bare_columns = bare_reference_columns | bare_trigger_columns
    if not bare_columns:
        return payload

    catalog = _table_column_catalog(table_schema)
    matching_tables = [
        table_id for table_id, columns in catalog.items() if bare_columns.issubset(columns)
    ]
    if len(matching_tables) != 1:
        raise ValueError(
            "cannot deterministically resolve bare Generation Rule Column references or triggers "
            f"{sorted(bare_columns)}; matching tables: {sorted(matching_tables)}"
        )

    table_id = matching_tables[0]
    normalized = dict(payload)
    normalized_properties = dict(properties)
    normalized_properties["references"] = [
        f"column.{table_id}.{reference.strip()}"
        if isinstance(reference, str) and reference.strip() in bare_reference_columns
        else reference
        for reference in references
    ]
    normalized_triggers = dict(triggers)
    normalized_sql_triggers = dict(sql_triggers)
    normalized_sql_triggers["columns"] = [
        f"column.{table_id}.{column.strip()}"
        if isinstance(column, str) and column.strip() in bare_trigger_columns
        else column
        for column in trigger_columns
    ]
    normalized_triggers["sql"] = normalized_sql_triggers
    normalized_properties["triggers"] = normalized_triggers
    normalized["properties"] = normalized_properties
    return normalized


def _table_column_catalog(table_schema: Any) -> dict[str, set[str]]:
    if not isinstance(table_schema, dict):
        return {}
    catalog: dict[str, set[str]] = {}
    for raw_table_id, raw_columns in table_schema.items():
        table_id = str(raw_table_id).strip()
        if not table_id:
            continue
        if isinstance(raw_columns, str):
            columns = set(re.findall(r"(?m)^\s*-\s*([^\s:]+)\s*:", raw_columns))
        elif isinstance(raw_columns, dict):
            columns = {str(column).strip() for column in raw_columns if str(column).strip()}
        else:
            columns = set()
        catalog[table_id] = columns
    return catalog
