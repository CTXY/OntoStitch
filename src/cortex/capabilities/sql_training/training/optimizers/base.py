class OptimizerAssetLLM(NodeModel):
    """Asset content generated by an Optimizer; runtime owns provenance and final ID."""

    id: str | None = Field(
        default=None,
        description="Omit for CREATE. Preserve the supplied asset ID for UPDATE or refinement.",
    )
    name: str = Field(description="Stable identity of the one asset being created or updated.")
    aliases: list[str] = Field(default_factory=list)
    description: str | None = None
    tags: list[str] = Field(default_factory=list)


class ConceptOptimizerAssetLLM(OptimizerAssetLLM):
    node_type: Literal["concept"]
    properties: ConceptProperties


